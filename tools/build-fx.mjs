// Renders the pixelfx effects the game uses into assets/fx/*.png and writes their frame data to js/fx-data.js.
// The data is a plain script (not JSON) so the game still runs from file:// with no server.
//   git clone https://github.com/patch-gg/pixelfx ../pixelfx
//   node tools/build-fx.mjs ../pixelfx
import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdirSync, readFileSync, writeFileSync, mkdtempSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const PFX = resolve(process.argv[2] || '../pixelfx');
const FIRE = ['#1f0b10', '#4a1118', '#8c1d1c', '#cc3a1a', '#f2701f', '#ffae35', '#ffe27a', '#fff8d6'];
const HOT = ['#3a1a08', '#7a3a10', '#c86a18', '#f2a030', '#ffd060', '#fff0a0', '#ffffff', '#ffffff'];
const ICE = ['#0c1430', '#162c5c', '#1f4f94', '#2f7fcc', '#58b4ec', '#9bdcff', '#d8f4ff', '#ffffff', '#ffffff'];
const BOG = ['#0d1a0c', '#173a14', '#265e18', '#3f8a1e', '#6cb82a', '#a8e04a', '#e0ff8a', '#f4ffd0', '#ffffff'];

// name: [pixelfx id, options]. the portal's rim is 9x12 px, which fills a 1.2 x 1.6 tile door at 15 px/tile
const FX = {
  portal: ['arcane/portal', { width: 9, height: 12, palette: FIRE }],
  'portal-hot': ['arcane/portal', { width: 9, height: 12, palette: HOT }],
  poof: ['spawn/poof', {}],
  torch: ['fire/torch', {}],
  'torch-blue': ['fire/torch', { palette: ICE }],
  'torch-green': ['fire/torch', { palette: BOG }],
  candle: ['fire/candle', {}],
  bat: ['critters/bat', {}],
  brazier: ['fire/brazier', {}],
  skull: ['critters/flying-skull', {}],
};

const out = join(ROOT, 'assets/fx'), tmp = mkdtempSync(join(tmpdir(), 'fx-'));
mkdirSync(out, { recursive: true });
const data = {};
for (const [name, [id, opts]] of Object.entries(FX)) {
  const dir = join(tmp, name), base = id.split('/')[1];
  execFileSync('node', ['tools/render.mjs', id, '--sheet', '--out', dir, '--opts', JSON.stringify(opts)], { cwd: PFX, stdio: 'pipe' });
  const src = join(dir, id, base);
  copyFileSync(`${src}.png`, join(out, `${name}.png`));
  const m = JSON.parse(readFileSync(`${src}.json`, 'utf8')).meta.pixelfx;
  data[name] = { w: m.frameSize[0], h: m.frameSize[1], px: m.pivot[0], py: m.pivot[1], cols: m.columns, n: m.frames, fps: m.fps, loop: m.loop };
  console.log(name.padEnd(12), id, `${m.frames}f`, m.frameSize.join('x'));
}
writeFileSync(join(ROOT, 'js/fx-data.js'), `// generated by tools/build-fx.mjs from pixelfx (MIT, https://github.com/patch-gg/pixelfx). do not edit.\nwindow.FX_DATA = ${JSON.stringify(data)};\n`);
